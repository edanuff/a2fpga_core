#!/usr/bin/env python3
"""Regenerate the accelerator probe's constraint files:

  accel_probe_138b.sdc     108 MHz, STEP_CLKS = 3, ADDR_CLKS = 2: 36 MHz steps
                           (shared by the three memory-size projects)
  accel_probe_138b_s2.sdc  100 MHz, STEP_CLKS = 2, ADDR_CLKS = 1: 50 MHz steps
                           (a2mega_accel_probe_138b_s2.gprj)
  accel_probe_138b_n2.sdc  100 MHz, the near-memory broker (NEAR): 50 MHz steps
                           (a2mega_accel_probe_138b_n2.gprj)

Each file is the timing contract of gs_accel_broker's data-late step, written
as multicycle exceptions between groups of registers and block-RAM pins.  A
core step is t; SLOW_CLKS = 3 in both.

Every pattern must match something in the netlist: the timing analyser stops
on a name that matches nothing (TA2003), e.g. a register synthesis removed.
"""
import pathlib, textwrap

def regs(*pats): return "[get_regs {" + " ".join(pats) + "}]"
def pins(*pats): return "[get_pins {" + " ".join(pats) + "}]"
def brk(*names): return [f"u_brk/{n}*" for n in names]

CORE = regs("u_cpu/*", "u_cpu/MCode/*", "u_cpu/AddrGen/*")
MEMQ = pins("*mram_*_s/CLKB", "*mrom_*_s/CLKB")            # the memories' read ports
ABR  = regs("*ram_sel_*", "*rom_sel_*")                    # block selects of their output muxes
SEL  = regs(*brk("use_lm_r", "rom_r"))                     # the data-source select
ADB  = pins("*mram_*_s/ADB*", "*mrom_*_s/ADB*")            # read address
WR   = pins("*mram_*_s/DI*", "*mram_*_s/CEA", "*mram_*_s/ADA*")
# registered at a launch (= a core step): addresses held, select, next step's status and decode
LAUN = regs(*brk("ld_phys", "ld_ram", "ld_rom", "use_lm_r", "rom_r", "pl_r_", "pl_w_", "pl_side",
                 "pl_int", "pl_we", "pl_vp_n", "pl_io_int", "pl_fresh", "ea_r"), "lm_raddr_q*")
# what the sequencer registers at or after the step's decision (never before t+2 with ADDR_CLKS = 2)
DEC  = brk("aq_", "pw_", "ml_", "st_", "ph_", "ce_r", "ce_c", "vfy_r", "ld_valid", "fl_",
           "stat_", "ev_", "ren_r", "ren_c")
BRK2 = regs(*DEC, "u_phy/*")
BRKD = regs(*DEC, *brk("sreq_data"), "u_phy/*")           # ... plus the write data a socket step passes on
PLD  = brk("pl_fresh", "pl_r_", "pl_w_", "pl_side")       # the step-ahead decode
PLS  = brk("pl_int", "pl_we", "pl_vp_n", "pl_io_int", "ea_r")   # the step-ahead status and the step's address
MODE = brk("mode_native", "mode_bypass")
ML   = regs(*brk("ml_sel_r", "ml_sel_c", "ml_phys", "ml_rom"))
REPL = regs("u_brk/u_replica/*")
VFY  = regs(*brk("verify_"))
AQ   = regs(*brk("aq_"))
WORD = {2: "two", 3: "three"}

def generate(STEP, ADDR, PERIOD, fname):
    out = []
    def mc(n, frm, to):
        out.append(f"set_multicycle_path {n} -setup -end -from {frm} -to {to}")
        out.append(f"set_multicycle_path {n - 1} -hold  -end -from {frm} -to {to}")
    def note(text):
        out.append("")
        out.extend("// " + l if l else "//" for l in textwrap.dedent(text).strip("\n").split("\n"))
    mhz = round(1000.0 / PERIOD)
    out.append(textwrap.dedent(f"""\
        // S7 accelerator timing probe (accel_probe_top): the accelerator domain at the
        // {mhz} MHz pin-sequencer clock, the core stepping every STEP_CLKS = {STEP} clks
        // ({mhz // STEP} MHz).  GENERATED by gen_sdc.py - edit that.  The exceptions below are the
        // timing contract gs_accel_broker documents and tb_gs_broker.sv asserts in clks
        // (step spacing, read launch -> use, select steady, no decision before the
        // second clk of a step, settle time of the registered decode); everything not
        // listed is an ordinary one-clk path.
        // See boards/a2mega/docs/gs_socket_s7_fast_core_exploration.md.
        create_clock -name clk{mhz} -period {PERIOD:.3f} -waveform {{0 {PERIOD / 2:.3f}}} [get_ports {{clk50_in}}]
        set_clock_uncertainty 0.5 -setup -from [get_clocks {{clk{mhz}}}]

        // gs_ph2 and the sequencer clock are asynchronous (hdl/twgs/gs_socket.sdc).  The
        // socket data byte (u_brk/d_f, PHI2-fall flops) is taken by the core the clk after
        // the synchronised fall event: at least three clks after the fall.
        create_clock -name gs_ph2 -period 349.0 -waveform {{209.4 349.0}} [get_ports {{gs_ph2}}]
        set_clock_groups -asynchronous -group [get_clocks {{gs_ph2}}] -group [get_clocks {{clk{mhz}}}]""").rstrip("\n"))

    note(f"""
        ---- STEP_CLKS-cycle paths ({WORD[STEP]} clks): launched at a core step, captured at the next.
        Startpoints: the core's registers; the memories' read ports and the block-select
        registers of their output muxes; the data-source select.
        Endpoints: the core's registers; the next read address (block pins and block
        selects); what the broker registers at the launch (addresses held, select, the
        next step's status and decode).""")
    for frm in (CORE, MEMQ, ABR, SEL):
        for to in (CORE, ADB, ABR, LAUN):
            mc(STEP, frm, to)

    if ADDR >= 2:
        note("""
            ---- ADDR_CLKS-cycle paths (two clks).  The step's decision hangs off broker
            registers only (the status and decode registered a step ahead, the mode) and is
            never made before the second clk of the step; the core's own outputs reach only
            what is passed on at or after the decision (addresses, write data) and the
            registered copy of the direct decode.
            A step's socket request IS registers loaded when the core steps (ea_r and the
            status); a native step raises its request flag in the first clk of the step from
            the mode alone, and the PHY takes the request two clks after the step at the
            soonest.  Not in these groups, ordinary one-clk paths: that flag, and the RAM
            write enable of a step decoded ahead (set in the first clk).""")
        mc(2, CORE, BRKD)
        mc(2, CORE, WR)
        mc(2, regs(*PLD, *PLS, *MODE), BRK2)
        mc(2, regs(*PLD, *PLS, *MODE), WR)
        mc(2, regs(*PLD), regs(*brk("sreq_")))
        mc(2, regs(*PLS), regs(*brk("sreq_data")))
        mc(2, regs(*PLD, *PLS), regs(*brk("sel_pw_r", "sel_sync_r")))             # (the mode reaches them in one clk: a native step's early request)
    else:
        note("""
            ---- ADDR_CLKS = 1: a step is decided in its first clk, so everything the
            decision is made from and everything it registers is an ordinary one-clk path.
            The one exception is the registered copy of the direct decode, which a step that
            was not decoded ahead gives SLOW_CLKS - 1 = two clks to settle.""")
        mc(2, CORE, AQ)
        mc(2, regs(*PLS), AQ)

    note("""
        ---- a read that was not launched ahead: its registered address is presented to
        the memories for two clks and launched in the second""")
    mc(2, ML, ADB)
    mc(2, ML, ABR)

    note("""
        ---- the broker's view of the core's reset changes at a PHI2-fall event; the PHY
        takes a cycle at its issue point, never sooner than two clks after one""")
    mc(2, regs(*brk("run_c")), regs("u_phy/*"))

    note("""
        ---- the registered copy of the direct decode (steady from the end of the second
        clk) gives a write that was not decoded ahead its RAM address; such a write is
        in the fourth clk""")
    mc(2, AQ, WR)

    note("""
        ---- verify (native, card memory of record): memory data against the socket byte, at
        the end of the socket cycle""")
    for frm in (MEMQ, ABR, SEL):
        mc(STEP, frm, VFY)

    note("""
        ---- the mode changes only when the core steps; it selects the interrupt lines the
        core sees and so reaches the next step's status""")
    mc(STEP, regs(*MODE), LAUN)

    note("""
        ---- the memory-map switches change at the end of a socket cycle; the step that
        follows is never decoded or launched ahead, so they reach a launch (address,
        decode) three clks later at the soonest and the registered copy of the direct
        decode two""")
    for to in (ADB, ABR, LAUN):
        mc(3, REPL, to)
    mc(2, REPL, AQ)

    note("""
        ---- the probe's stand-ins for the control plane (ESP32 in the real build): the
        configuration register, quasi-static and changed with the core held in reset,
        and the ROM-image loader port, used at bring-up only""")
    out.append("set_false_path -from [get_regs {cfg_*}]")
    out.append("set_false_path -from [get_regs {ld_a_* ld_d_* ld_we_*}]")

    pathlib.Path(__file__).with_name(fname).write_text("\n".join(out) + "\n")
    print(f"{fname}: {sum(1 for l in out if l.startswith('set_multicycle'))} exception lines")

def generate_near(PERIOD, fname, pfx="", board=False):
    """The near-memory broker's contract: far fewer exceptions, because nothing is decoded ahead.

    pfx: hierarchy in front of u_brk / u_cpu / u_phy and the memories ("u_acc/" in gs_accel).
    board: the accelerator-only board build (hdl/accel_only): its clocks, no probe stand-ins.
    """
    out = []
    def mc(n, frm, to):
        out.append(f"set_multicycle_path {n} -setup -end -from {frm} -to {to}")
        out.append(f"set_multicycle_path {n - 1} -hold  -end -from {frm} -to {to}")
    def note(text):
        out.append("")
        out.extend("// " + l if l else "//" for l in textwrap.dedent(text).strip("\n").split("\n"))
    def b(*names): return [f"{pfx}u_brk/{n}*" for n in names]
    mhz = round(1000.0 / PERIOD)
    if board:
        out.append(textwrap.dedent(f"""\
            // Accelerator-only build (hdl/accel_only/accel_only_top.sv, a2mega_accel_138B.gprj):
            // the accelerator domain (gs_accel) on clk_gs, the S6 socket PLL ({mhz} MHz), the core
            // stepping every two clks ({mhz / 2:g} MHz); the ESP32 connector on clk_logic.
            // GENERATED by hdl/accel_probe_138b/gen_sdc.py - edit that.
            // The exceptions are the timing contract gs_accel_broker (NEAR) documents and
            // tb_gs_broker.sv asserts in clks, as in the probe (accel_probe_138b_n8.sdc);
            // everything not listed is an ordinary one-clk path.
            // See boards/a2mega/docs/gs_socket_s7_fast_core_exploration.md.
            create_clock -name clk -period 20 -waveform {{0 10}} [get_ports {{clk}}]
            // clk_logic: the board PLL's fractional 54 MHz output, constrained at its worst
            // instantaneous period as in a2mega_138b.sdc
            create_clock -name clk_logic -period 17.777 -waveform {{0 8.888}} [get_pins {{i_clk_pll/u_pll/PLL_inst/CLKOUT0}}]
            create_clock -name clk_gs -period {PERIOD:.3f} -waveform {{0 {PERIOD / 2:.3f}}} [get_pins {{i_gs_pll/u_pll/PLL_inst/CLKOUT0}}]
            set_clock_uncertainty 0.5 -setup -from [get_clocks {{clk_gs}}]
            set_clock_uncertainty 0.5 -setup -from [get_clocks {{clk_logic}}]

            // gs_ph2 (the FPI's PHI2 at the socket) and the three clocks are asynchronous to one
            // another: the socket data byte (d_f, PHI2-fall flops) is registered in the clk_gs
            // domain a clk and more after the fall; control and telemetry between clk_logic and
            // clk_gs are quasi-static and two-flopped (accel_only_top.sv).
            create_clock -name gs_ph2 -period 349.0 -waveform {{209.4 349.0}} [get_ports {{gs_ph2}}]
            set_clock_groups -asynchronous -group [get_clocks {{gs_ph2}}] -group [get_clocks {{clk_gs}}] -group [get_clocks {{clk}}] -group [get_clocks {{clk_logic}}]""").rstrip("\n"))
    else:
        out.append(textwrap.dedent(f"""\
            // S7 accelerator timing probe (accel_probe_top, ACCEL_PROBE_NEAR): the accelerator
            // domain at the {mhz} MHz pin-sequencer clock, the core stepping every two clks
            // ({mhz / 2:g} MHz) from the near memory.  GENERATED by gen_sdc.py - edit that.
            // The exceptions are the timing contract gs_accel_broker (NEAR) documents and
            // tb_gs_broker.sv asserts in clks; everything not listed is an ordinary one-clk
            // path - in particular the cheap view of a step and the tag compare (the step's
            // first clk) and the clock enable made from them (its second).
            // See boards/a2mega/docs/gs_socket_s7_fast_core_exploration.md.
            create_clock -name clk{mhz} -period {PERIOD:.3f} -waveform {{0 {PERIOD / 2:.3f}}} [get_ports {{clk50_in}}]
            set_clock_uncertainty 0.5 -setup -from [get_clocks {{clk{mhz}}}]

            // gs_ph2 and the sequencer clock are asynchronous (hdl/twgs/gs_socket.sdc).  The
            // socket data byte (u_brk/d_f, PHI2-fall flops) is registered in the clk domain
            // (alt_q) a clk and more after the fall, and steady there when the core takes it.
            create_clock -name gs_ph2 -period 349.0 -waveform {{209.4 349.0}} [get_ports {{gs_ph2}}]
            set_clock_groups -asynchronous -group [get_clocks {{gs_ph2}}] -group [get_clocks {{clk{mhz}}}]""").rstrip("\n"))
    CORE = regs(f"{pfx}u_cpu/*", f"{pfx}u_cpu/MCode/*", f"{pfx}u_cpu/AddrGen/*")
    NMQ  = pins("*nmem_*_s/CLKB")                               # the near memory's read port
    NADB = pins("*nmem_*_s/ADB*")                               # ... its read address
    SELN = regs(*b("near_r"))                                   # the core's data select
    ALT  = regs(*b("alt_q"))                                    # ... and its other source
    STEPR = regs(*b("ea_r", "pl_int", "pl_we", "pl_vp_n", "pl_io_int", "nl_idx", "nl_ok"))   # loaded when the core steps
    LATE = regs(*b("wd_r", "sreq_data", "pw_data"), f"{pfx}u_phy/*")                         # ... at the step's decision or later
    FADB = pins("*mram_*_s/ADB*", "*mrom_*_s/ADB*")             # the far memories' read addresses
    FSEL = regs("*ram_sel_*", "*rom_sel_*")                     # block selects of their output muxes
    note("""
        ---- step paths (two clks): launched when the core steps, captured when it steps
        again.  Startpoints: the core's registers, the near memory's read port, the
        core's data select and its other data source (steady for two clks before a step
        that uses it).  Endpoints: the core's registers, the near memory's read address,
        and what the broker loads from the core when it steps (the step's address and
        status, the index of the launch).""")
    for frm in (CORE, NMQ, SELN, ALT):
        for to in (CORE, NADB, STEPR):
            mc(2, frm, to)
    note("""
        ---- the mode changes only when the core steps; it selects the interrupt lines the
        core sees, which reach its registers and (through its next status) the step registers""")
    for to in (CORE, STEPR):
        mc(2, regs(*b("mode_native", "mode_bypass")), to)
    note("""
        ---- the interrupt lines the core sees: in fast mode held from one core step to
        the next; in native mode the pads of the PHI2 fall, in a register from the
        second clk edge after it, two clks before the step""")
    for to in (CORE, STEPR):
        mc(2, regs(*b("irq_h", "nmi_h", "abort_h", "irq_e", "nmi_e", "abort_e")), to)
    note("""
        ---- (stated, not relaxed) the core's clock enable is one gate behind registers,
        and reaches the core in one clk""")
    out.append(f"set_max_delay {PERIOD:.3f} -from {regs(*b('ce_c', 'ce_r', 'fa_c', 'fb_c', 'fh_c'))} -to {CORE}")
    note("""
        ---- the full decode of a step: from the step registers (and the memory-map
        switches, which change three clks and more before it is used) to its registered
        copy and the tag compare made from it, used from the step's third clk""")
    FULL = regs(*b("aq_", "nh_dq"))
    # (not nl_ok: a write in the step's first clk clears it, and the compare must see that in the second)
    mc(2, regs(*b("ea_r", "ea_k", "pl_int", "pl_we", "pl_vp_n", "pl_io_int")), FULL)
    mc(2, regs(f"{pfx}u_brk/u_replica/*"), FULL)
    if board:
        # (gs_accel takes it only with the core in reset or held)
        mc(2, regs(f"{pfx}cxrom*"), FULL)
    note("""
        ---- the core's outputs reach the broker's other registers no sooner than the
        step's second clk: write data (registered with the write, with a socket request,
        with a posted write) and the PHY's request (the idle address during reset)""")
    mc(2, CORE, LATE)
    note("""
        ---- a far read: its registered address is presented to the memories for two
        clks and launched in the second""")
    mc(2, regs(*b("ml_sel_r", "ml_sel_c", "ml_phys", "ml_rom")), FADB)
    mc(2, regs(*b("ml_sel_r", "ml_sel_c", "ml_phys", "ml_rom")), FSEL)
    if board:
        note("""
            ---- ... and (gs_accel: FAR_CLKS = 2) its data has two clks from the memories'
            read ports and their block selects to the broker's register""")
        mc(2, pins("*mram_*_s/CLKB", "*mrom_*_s/CLKB"), ALT)
        mc(2, FSEL, ALT)
    note("""
        ---- the broker's view of the core's reset changes at a PHI2-fall event; the PHY
        takes a cycle at its issue point, never sooner than two clks after one""")
    mc(2, regs(*b("run_c")), regs(f"{pfx}u_phy/*"))
    if board:
        note("""
            ---- the ROM copy (gs_accel_romcopy): a byte's address and data are registered
            two clks before its write enable, which lasts two clks; a near-memory index
            is flushed for two clks""")
        CP = f"{pfx}u_copy/"
        mc(2, regs(CP + "rom_wa_o*", CP + "rom_wd_o*", CP + "rom_we_o*"), pins("*mrom_*_s/ADA*", "*mrom_*_s/DI*", "*mrom_*_s/CEA"))
        mc(2, regs(CP + "cs*", CP + "f_*"), pins("*nmem_*_s/ADA*", "*nmem_*_s/DI*", "*nmem_*_s/CEA"))
        note("""
            ---- the telemetry word's index: quasi-static (the firmware writes it, then reads)""")
        out.append("set_false_path -from [get_regs {gs_ti_s1*}]")
    if not board:
        note("""
            ---- the probe's stand-ins for the control plane (ESP32 in the real build): the
            configuration register, quasi-static and changed with the core held in reset,
            and the ROM-image loader port, used at bring-up only""")
        out.append("set_false_path -from [get_regs {cfg_*}]")
        out.append("set_false_path -from [get_regs {ld_a_* ld_d_* ld_we_*}]")
        note("""
            ---- the probe's power-up reset (a counter in the top level, one net to every
            register's clear): released once, long before the socket is armed""")
        out.append("set_false_path -from [get_regs {rst_cnt_*}]")
    note("""
        ---- (report only) one path per endpoint, for a wider view of the step paths
        than the default table""")
    out.append("report_timing -setup -max_paths 400 -max_common_paths 1")
    dst = pathlib.Path(__file__).parent.parent / "accel_only" / fname if board else pathlib.Path(__file__).with_name(fname)
    dst.write_text("\n".join(out) + "\n")
    print(f"{fname}: {sum(1 for l in out if l.startswith('set_multicycle'))} exception lines")

generate(3, 2, 9.259, "accel_probe_138b.sdc")
generate(2, 1, 10.000, "accel_probe_138b_s2.sdc")
generate_near(10.000, "accel_probe_138b_n2.sdc")
generate_near(9.259, "accel_probe_138b_n8.sdc")      # the same design at 108 MHz: 54 MHz steps
generate_near(9.091, "accel_only_138b.sdc", pfx="u_acc/", board=True)   # the board build: the S6 socket PLL, 110 MHz
