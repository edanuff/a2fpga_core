#!/usr/bin/env python3
"""Regenerate the accelerator probe's constraint files:

  accel_probe_138b.sdc     108 MHz, STEP_CLKS = 3, ADDR_CLKS = 2: 36 MHz steps
                           (shared by the three memory-size projects)
  accel_probe_138b_s2.sdc  100 MHz, STEP_CLKS = 2, ADDR_CLKS = 1: 50 MHz steps
                           (a2mega_accel_probe_138b_s2.gprj)

Each file is the timing contract of gs_accel_broker's data-late step, written
as multicycle exceptions between groups of registers and block-RAM pins.  A
core step is t; SLOW_CLKS = 3 in both.

Every pattern must match something in the netlist: the timing analyser stops
on a name that matches nothing (TA2003), e.g. a register synthesis removed.
"""
import pathlib, textwrap

def regs(*pats): return "[get_regs {" + " ".join(pats) + "}]"
def pins(*pats): return "[get_pins {" + " ".join(pats) + "}]"
def brk(*names): return [f"u_brk/{n}*" for n in names]

CORE = regs("u_cpu/*", "u_cpu/MCode/*", "u_cpu/AddrGen/*")
MEMQ = pins("*mram_*_s/CLKB", "*mrom_*_s/CLKB")            # the memories' read ports
ABR  = regs("*ram_sel_*", "*rom_sel_*")                    # block selects of their output muxes
SEL  = regs(*brk("use_lm_r", "rom_r"))                     # the data-source select
ADB  = pins("*mram_*_s/ADB*", "*mrom_*_s/ADB*")            # read address
WR   = pins("*mram_*_s/DI*", "*mram_*_s/CEA", "*mram_*_s/ADA*")
# registered at a launch (= a core step): addresses held, select, next step's status and decode
LAUN = regs(*brk("ld_phys", "ld_ram", "ld_rom", "use_lm_r", "rom_r", "pl_r_", "pl_w_", "pl_side",
                 "pl_int", "pl_we", "pl_vp_n", "pl_io_int", "pl_fresh", "ea_r"), "lm_raddr_q*")
# what the sequencer registers at or after the step's decision (never before t+2 with ADDR_CLKS = 2)
DEC  = brk("aq_", "pw_", "ml_", "st_", "ph_", "ce_r", "ce_c", "vfy_r", "ld_valid", "fl_",
           "stat_", "ev_", "ren_r", "ren_c")
BRK2 = regs(*DEC, "u_phy/*")
BRKD = regs(*DEC, *brk("sreq_data"), "u_phy/*")           # ... plus the write data a socket step passes on
PLD  = brk("pl_fresh", "pl_r_", "pl_w_", "pl_side")       # the step-ahead decode
PLS  = brk("pl_int", "pl_we", "pl_vp_n", "pl_io_int", "ea_r")   # the step-ahead status and the step's address
MODE = brk("mode_native", "mode_bypass")
ML   = regs(*brk("ml_sel_r", "ml_sel_c", "ml_phys", "ml_rom"))
REPL = regs("u_brk/u_replica/*")
VFY  = regs(*brk("verify_"))
AQ   = regs(*brk("aq_"))
WORD = {2: "two", 3: "three"}

def generate(STEP, ADDR, PERIOD, fname):
    out = []
    def mc(n, frm, to):
        out.append(f"set_multicycle_path {n} -setup -end -from {frm} -to {to}")
        out.append(f"set_multicycle_path {n - 1} -hold  -end -from {frm} -to {to}")
    def note(text):
        out.append("")
        out.extend("// " + l if l else "//" for l in textwrap.dedent(text).strip("\n").split("\n"))
    mhz = round(1000.0 / PERIOD)
    out.append(textwrap.dedent(f"""\
        // S7 accelerator timing probe (accel_probe_top): the accelerator domain at the
        // {mhz} MHz pin-sequencer clock, the core stepping every STEP_CLKS = {STEP} clks
        // ({mhz // STEP} MHz).  GENERATED by gen_sdc.py - edit that.  The exceptions below are the
        // timing contract gs_accel_broker documents and tb_gs_broker.sv asserts in clks
        // (step spacing, read launch -> use, select steady, no decision before the
        // second clk of a step, settle time of the registered decode); everything not
        // listed is an ordinary one-clk path.
        // See boards/a2mega/docs/gs_socket_s7_fast_core_exploration.md.
        create_clock -name clk{mhz} -period {PERIOD:.3f} -waveform {{0 {PERIOD / 2:.3f}}} [get_ports {{clk50_in}}]
        set_clock_uncertainty 0.5 -setup -from [get_clocks {{clk{mhz}}}]

        // gs_ph2 and the sequencer clock are asynchronous (hdl/twgs/gs_socket.sdc).  The
        // socket data byte (u_brk/d_f, PHI2-fall flops) is taken by the core the clk after
        // the synchronised fall event: at least three clks after the fall.
        create_clock -name gs_ph2 -period 349.0 -waveform {{209.4 349.0}} [get_ports {{gs_ph2}}]
        set_clock_groups -asynchronous -group [get_clocks {{gs_ph2}}] -group [get_clocks {{clk{mhz}}}]""").rstrip("\n"))

    note(f"""
        ---- STEP_CLKS-cycle paths ({WORD[STEP]} clks): launched at a core step, captured at the next.
        Startpoints: the core's registers; the memories' read ports and the block-select
        registers of their output muxes; the data-source select.
        Endpoints: the core's registers; the next read address (block pins and block
        selects); what the broker registers at the launch (addresses held, select, the
        next step's status and decode).""")
    for frm in (CORE, MEMQ, ABR, SEL):
        for to in (CORE, ADB, ABR, LAUN):
            mc(STEP, frm, to)

    if ADDR >= 2:
        note("""
            ---- ADDR_CLKS-cycle paths (two clks).  The step's decision hangs off broker
            registers only (the status and decode registered a step ahead, the mode) and is
            never made before the second clk of the step; the core's own outputs reach only
            what is passed on at or after the decision (addresses, write data) and the
            registered copy of the direct decode.
            A step's socket request IS registers loaded when the core steps (ea_r and the
            status); a native step raises its request flag in the first clk of the step from
            the mode alone, and the PHY takes the request two clks after the step at the
            soonest.  Not in these groups, ordinary one-clk paths: that flag, and the RAM
            write enable of a step decoded ahead (set in the first clk).""")
        mc(2, CORE, BRKD)
        mc(2, CORE, WR)
        mc(2, regs(*PLD, *PLS, *MODE), BRK2)
        mc(2, regs(*PLD, *PLS, *MODE), WR)
        mc(2, regs(*PLD), regs(*brk("sreq_")))
        mc(2, regs(*PLS), regs(*brk("sreq_data")))
        mc(2, regs(*PLD, *PLS), regs(*brk("sel_pw_r", "sel_sync_r")))             # (the mode reaches them in one clk: a native step's early request)
    else:
        note("""
            ---- ADDR_CLKS = 1: a step is decided in its first clk, so everything the
            decision is made from and everything it registers is an ordinary one-clk path.
            The one exception is the registered copy of the direct decode, which a step that
            was not decoded ahead gives SLOW_CLKS - 1 = two clks to settle.""")
        mc(2, CORE, AQ)
        mc(2, regs(*PLS), AQ)

    note("""
        ---- a read that was not launched ahead: its registered address is presented to
        the memories for two clks and launched in the second""")
    mc(2, ML, ADB)
    mc(2, ML, ABR)

    note("""
        ---- the broker's view of the core's reset changes at a PHI2-fall event; the PHY
        takes a cycle at its issue point, never sooner than two clks after one""")
    mc(2, regs(*brk("run_c")), regs("u_phy/*"))

    note("""
        ---- the registered copy of the direct decode (steady from the end of the second
        clk) gives a write that was not decoded ahead its RAM address; such a write is
        in the fourth clk""")
    mc(2, AQ, WR)

    note("""
        ---- verify (native, card memory of record): memory data against the socket byte, at
        the end of the socket cycle""")
    for frm in (MEMQ, ABR, SEL):
        mc(STEP, frm, VFY)

    note("""
        ---- the mode changes only when the core steps; it selects the interrupt lines the
        core sees and so reaches the next step's status""")
    mc(STEP, regs(*MODE), LAUN)

    note("""
        ---- the memory-map switches change at the end of a socket cycle; the step that
        follows is never decoded or launched ahead, so they reach a launch (address,
        decode) three clks later at the soonest and the registered copy of the direct
        decode two""")
    for to in (ADB, ABR, LAUN):
        mc(3, REPL, to)
    mc(2, REPL, AQ)

    note("""
        ---- the probe's stand-ins for the control plane (ESP32 in the real build): the
        configuration register, quasi-static and changed with the core held in reset,
        and the ROM-image loader port, used at bring-up only""")
    out.append("set_false_path -from [get_regs {cfg_*}]")
    out.append("set_false_path -from [get_regs {ld_a_* ld_d_* ld_we_*}]")

    pathlib.Path(__file__).with_name(fname).write_text("\n".join(out) + "\n")
    print(f"{fname}: {sum(1 for l in out if l.startswith('set_multicycle'))} exception lines")

generate(3, 2, 9.259, "accel_probe_138b.sdc")
generate(2, 1, 10.000, "accel_probe_138b_s2.sdc")
